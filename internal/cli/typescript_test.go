const tsUsers = `import { Db } from "./db";

export async function loadUser(db: Db, userId: number): Promise<User> {
  const row = await db.queryRow("SELECT * FROM users WHERE id = $1", [userId]);
  if (!row) {
    throw new NotFoundError(` + "`user ${userId}`" + `);
  }
  const { name, email } = row;
  if (name === "") {
    throw new Error("user has no name");
  }
  return new User(name, email);
}
`

func TestCheckReportsCopiesInTypeScriptCode(t *testing.T) {
	tsOrders := strings.NewReplacer("loadUser", "loadOrder", "userId", "orderId", "users", "orders", "User", "Order", "user", "order").Replace(tsUsers)
	root := repo(t, map[string]string{
		"src/users.ts":      tsUsers,
		"web/orders.tsx":    tsOrders,
		"src/users.test.ts": strings.Replace(tsUsers, "loadUser", "loadUserFixture", 1), // a test helper: compared with test code only
		"src/generated.ts":  "// Code generated by openapi-generator. DO NOT EDIT.\n\n" + strings.Replace(tsUsers, "loadUser", "loadUserGen", 1),
		"types/users.d.ts":  "export declare function loadUser(db: Db, userId: number): Promise<User>;\n",
		"store/users.go":    goUsers,
		"store/orders.go":   strings.NewReplacer("LoadUser", "LoadOrder", "userID", "orderID", "users", "orders", "user %d", "order %d").Replace(goUsers),
	})

	code, stdout, stderr := run("check", "--format", "json", "--min-nodes", "20", root)

	if code != 1 {
		t.Fatalf("exit code = %d, want 1; stderr: %s", code, stderr)
	}
	r := decode(t, stdout)
	testutil.Lines(t, "candidates", candidateLines(r), []string{
		"go renamed-clone [store/orders.go LoadOrder, store/users.go LoadUser]",
		"typescript renamed-clone [src/users.ts loadUser, web/orders.tsx loadOrder]",
	})
	// The declaration file is not analysed.
	if r.Summary.GeneratedFiles != 1 || r.Summary.Files != 5 {
		t.Errorf("summary = %+v, want 5 files, 1 of them generated", r.Summary)
	}
}

// TypeScript calls through package imports are not followed, so no
// exported function is known to be unused, even in an unpublished Rust
// crate's directory (a Tauri app's frontend).
func TestTypeScriptExportsAreNotReportedUnused(t *testing.T) {
	root := repo(t, map[string]string{
		"Cargo.toml":    "[package]\nname = \"app\"\npublish = false\n",
		"src/main.rs":   "fn main() {}\n",
		"src/users.ts":  tsUsers,
		"src/orders.ts": strings.Replace(tsUsers, "loadUser", "loadOrder", 1),
	})

	_, stdout, stderr := run("check", "--format", "json", "--min-nodes", "20", root)

	for _, c := range decode(t, stdout).Candidates {
		if c.Kind == "dead-code" {
			t.Errorf("reported %s as unused; stderr: %s", c.Occurrences[0].Name, stderr)
		}
	}
}

func TestCheckReportsTypeScriptTypesAndConstantsDeclaredAgain(t *testing.T) {
	billing := `export const MAX_GRANTED_MODELS = 64;

export const CODE_UNAVAILABLE = "ledger_unavailable";

export interface Budget {
  id: string;
  limit: number;
  spent: number;
  updatedAt: Date;
}

export type RunState = "queued" | "running" | "done";

export function refuse(code: string): boolean {
  return code === "ledger_unavailable";
}
`
	reports := `export const MAX_GRANTED_MODELS = 64;

export type Budget = {
  id: string;
  limit: number;
  spent: number;
  updatedAt: Date;
};

export enum JobState { Done = "done", Queued = "queued", Running = "running" }

export type Phase = "queued" | "running" | "done";
`
	root := repo(t, map[string]string{"src/billing/billing.ts": billing, "src/reports/reports.ts": reports})

	_, stdout, _ := run("check", "--format", "json", root)

	// An enum with values is not the union of those values: its variants
	// have names.
	testutil.Lines(t, "candidates", candidateLines(decode(t, stdout)), []string{
		"typescript duplicate-type [src/billing/billing.ts Budget, src/reports/reports.ts Budget]",
		"typescript duplicate-type [src/billing/billing.ts RunState, src/reports/reports.ts Phase]",
		"typescript duplicate-constant [src/billing/billing.ts MAX_GRANTED_MODELS, src/reports/reports.ts MAX_GRANTED_MODELS]",
		"typescript inlined-constant [src/billing/billing.ts CODE_UNAVAILABLE, src/billing/billing.ts refuse]",
	})
}

const (
	tsLoad = `import { parse } from "../codec/parse";

export function loadRow(id: string, raw: string) {
  const row = parse(raw);
  if (!row) {
    throw new Error("no row " + id);
  }
  return row;
}

export function encode(value: unknown) {
  return JSON.stringify(value);
}
`
	tsParse = `import { encode } from "../store/load.js";

export function parse(raw: string) {
  return JSON.parse(raw);
}

export const fetchRow = (id: string, raw: string) => loadRow(id, raw);

export function save(value: unknown) {
  return encode(value);
}

export class Repo {
  load(id: string, raw: string) {
    return loadRow(id, raw);
  }
}

function loadRow(id: string, raw: string) {
  return { id, raw };
}
`
)

func TestCheckReportsTypeScriptWrappers(t *testing.T) {
	root := repo(t, map[string]string{"src/store/load.ts": tsLoad, "src/codec/parse.ts": tsParse})

	_, stdout, _ := run("check", "--format", "json", root)

	// save wraps encode; fetchRow wraps the file's own loadRow, not the
	// other file's, which it does not import. A class method may be what
	// an interface asks for: no wrapper.
	testutil.Lines(t, "candidates", candidateLines(decode(t, stdout)), []string{
		"typescript pass-through [src/codec/parse.ts fetchRow]",
		"typescript pass-through [src/codec/parse.ts save]",
	})
}

// Module cycles are found among a Rust crate's modules; TypeScript calls
// in the crate's directory (a Tauri app's frontend) are none of them.
func TestTypeScriptCallsCloseNoRustCycle(t *testing.T) {
	root := repo(t, map[string]string{
		"Cargo.toml":         "[package]\nname = \"app\"\n",
		"src/lib.rs":         "pub mod store;\n",
		"src/store.rs":       "pub fn get() {}\n",
		"src/store/load.ts":  tsLoad,
		"src/codec/parse.ts": tsParse,
	})

	_, stdout, stderr := run("check", "--format", "json", root)

	for _, c := range decode(t, stdout).Candidates {
		if c.Kind == "dependency-cycle" {
			t.Errorf("reported a cycle through %+v; stderr: %s", c.Occurrences, stderr)
		}
	}
}

func TestCheckReportsTypeScriptParameterGroupsAndStringKinds(t *testing.T) {
	root := repo(t, map[string]string{
		"src/billing.ts": `export function charge(tenantId: string, region: string, plan: Plan, amount: number) {
  return post("/charge", { tenantId, region, plan, amount });
}

export function refund(tenantId: string, region: string, plan: Plan) {
  return post("/refund", { tenantId, region, plan });
}

export const quote = (tenantId: string, region: string, plan: Plan, seats: number) => price(plan, seats) + tax(region, tenantId);

export function invoice(plan: Plan, region: string, tenantId: string, at: Date) {
  return render(at, plan, region, tenantId);
}

export class Billing {
  bill(tenantId: string, region: string, plan: Plan) {
    return charge(tenantId, region, plan, 0);
  }
}
`,
		"src/state.ts": `export function label(state: string) {
  switch (state) {
    case "queued": return "Waiting";
    case "running": return "Busy";
    case "done": return "Finished";
  }
  return "";
}

export function icon(state: string) {
  switch (state) {
    case 'queued': return clock();
    case 'running': return spinner();
    case 'done': return check();
  }
}

export function canCancel(state: string): boolean {
  switch (state) {
    case "queued":
    case "running":
      return true;
    case "done":
      return false;
  }
  return false;
}
`,
	})

	_, stdout, _ := run("check", "--format", "json", root)

	// A class method may be what an interface asks for: its parameters
	// are dictated. Quote style is formatting.
	testutil.Lines(t, "candidates", candidateLines(decode(t, stdout), "parameter-group", "string-kinds"), []string{
		"typescript parameter-group [src/billing.ts charge, src/billing.ts refund, src/billing.ts quote, src/billing.ts invoice]",
		"typescript string-kinds [src/state.ts label, src/state.ts icon, src/state.ts canCancel]",
	})
}
