package cli

import (
	"fmt"
	"path/filepath"
	"strings"
	"testing"
)

const goUsers = `package store

func LoadUser(db *DB, userID int) (*User, error) {
	row, err := db.QueryRow("SELECT * FROM users WHERE id = $1", userID)
	if err != nil {
		return nil, err
	}
	var name, email string
	if err := row.Scan(&name, &email); err != nil {
		return nil, fmt.Errorf("user %d: %w", userID, err)
	}
	if name == "" {
		return nil, ErrNotFound
	}
	return &User{Name: name, Email: email}, nil
}
`

func TestCheckReportsCopiesInGoCode(t *testing.T) {
	goOrders := strings.NewReplacer("LoadUser", "LoadOrder", "userID", "orderID", "users", "orders", "user %d", "order %d").Replace(goUsers)
	root := repo(t, map[string]string{
		"store/users.go":      goUsers,
		"store/orders.go":     goOrders,
		"store/users_test.go": strings.Replace(goUsers, "LoadUser", "loadUserFixture", 1),
		"store/generated.go":  "// Code generated by sqlc. DO NOT EDIT.\n\n" + strings.Replace(goUsers, "LoadUser", "LoadUserGen", 1),
		"src/users.rs":        users,
		"src/orders.rs":       orders,
	})

	code, stdout, stderr := run("check", "--format", "json", "--min-nodes", "20", root)

	if code != 1 {
		t.Fatalf("exit code = %d, want 1; stderr: %s", code, stderr)
	}
	r := decode(t, stdout)
	var got []string
	for _, c := range r.Candidates {
		var occs []string
		for _, o := range c.Occurrences {
			occs = append(occs, filepath.ToSlash(o.File)+" "+o.Name)
		}
		got = append(got, fmt.Sprintf("%s %s %s [%s]", c.Language, c.Kind, strings.SplitN(c.Fingerprint, ":", 2)[0], strings.Join(occs, ", ")))
	}
	want := []string{
		"go renamed-clone go [store/orders.go LoadOrder, store/users.go LoadUser]",
		"rust renamed-clone rust [src/orders.rs load_order, src/users.rs load_user]",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("candidates:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	if r.Summary.GeneratedFiles != 1 || r.Summary.TestUnits != 1 {
		t.Errorf("summary = %+v, want 1 generated file and 1 test function", r.Summary)
	}
}

func TestCheckReportsGoTypesAndConstantsDeclaredAgain(t *testing.T) {
	billing := `package billing

const MaxGrantedModels = 64

const CodeUnavailable = "ledger_unavailable"

type Budget struct {
	ID        string
	Limit     int64
	Spent     int64
	UpdatedAt time.Time
}

func refuse(code string) bool {
	return code == "ledger_unavailable"
}
`
	reports := `package reports

const MaxGrantedModels = 64

type Budget struct {
	ID        string
	Limit     int64
	Spent     int64
	UpdatedAt time.Time
}
`
	root := repo(t, map[string]string{"billing/billing.go": billing, "reports/reports.go": reports})

	_, stdout, stderr := run("check", "--format", "json", root)

	var got []string
	for _, c := range decode(t, stdout).Candidates {
		var occs []string
		for _, o := range c.Occurrences {
			occs = append(occs, filepath.ToSlash(o.File)+" "+o.Name)
		}
		got = append(got, fmt.Sprintf("%s %s [%s]", c.Language, c.Kind, strings.Join(occs, ", ")))
	}
	want := []string{
		"go duplicate-type [billing/billing.go Budget, reports/reports.go Budget]",
		"go duplicate-constant [billing/billing.go MaxGrantedModels, reports/reports.go MaxGrantedModels]",
		"go inlined-constant [billing/billing.go CodeUnavailable, billing/billing.go refuse]",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("candidates:\n%s\nwant:\n%s\nstderr: %s", strings.Join(got, "\n"), strings.Join(want, "\n"), stderr)
	}
}
