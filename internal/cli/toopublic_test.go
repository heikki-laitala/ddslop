// A pub function or constant of an unpublished crate's library that
// only the library uses can be pub(crate). Code compiled outside the
// library keeps it pub: another crate, the crate's tests, a binary, a
// doc test (in an included README too), an exported macro, a re-export.
// So do an item read from outside the source (#[no_mangle]), one only
// some builds use (the library's tests, code under a #[cfg] or
// #![cfg]), one only a comment names besides, one of a published crate
// and one of a crate with no library. A name two items declare is no use
// of either.
func TestCheckReportsRustItemsOnlyTheirCrateUses(t *testing.T) {
	root := repo(t, map[string]string{
		"Cargo.toml":             "[workspace]\nmembers = [\"crates/*\"]\n\n[workspace.package]\npublish = false\n",
		"crates/util/Cargo.toml": "[package]\nname = \"util\"\npublish.workspace = true\n",
		"crates/util/GUIDE.md":   "```\nutil::guide_helper();\n```\n",
		"crates/util/README.md":  "# util\n\n```\nutil::readme_helper();\n```\n",
		"crates/util/src/lib.rs": `#![doc = include_str!("../README.md")]

pub mod text;

pub struct Store;

impl Store {
    pub fn reset(&self) {}
}

pub fn shared() {}

pub fn helper() {}

pub fn tested() {}

/// Runs the example.
///
/// ` + "```" + `
/// util::documented();
/// ` + "```" + `
pub fn documented() {}

pub fn by_macro() {}

pub mod generated;

pub fn readme_helper() {}

pub fn guide_helper() {}

#[macro_export]
macro_rules! call {
    () => {
        $crate::by_macro()
    };
}

pub(crate) fn narrow() {}

pub use text::reexported;

pub fn only_tested() {}

#[cfg(target_os = "macos")]
mod real;

pub fn mac_only() {}

mod gated;

pub fn gated_only() {}

#[cfg(unix)]
mod sys {
    mod imp;
}

pub fn unix_only() {}

/// Not [linked] in code.
pub fn linked() {}

pub const LIMIT: u32 = 3;

pub const SCRIPT: &str = "lib";

#[cfg(test)]
fn script() -> &'static str {
    SCRIPT
}

pub static SHOWN: &str = "cli";

#[no_mangle]
pub static EXPORTED: u32 = 1;

#[cfg(test)]
mod tests {
    #[test]
    fn works() {
        super::only_tested();
    }

    #[test]
    fn helper() {}
}

#[no_mangle]
pub extern "C" fn ffi() {}
`,
		"crates/util/src/text.rs":      "#![doc = include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/GUIDE.md\"))]\n\npub const SCRIPT: &str = \"text\";\n\n#[cfg(test)]\nfn script() -> &'static str {\n    SCRIPT\n}\n\npub fn gen_reexported() {}\n\npub fn reexported() {}\n\npub fn run(s: &crate::Store) {\n    s.reset();\n    crate::helper();\n    crate::tested();\n    crate::documented();\n    crate::by_macro();\n    crate::readme_helper();\n    crate::guide_helper();\n    crate::narrow();\n    crate::ffi();\n    gen_reexported();\n    reexported();\n    let _ = (crate::LIMIT, crate::EXPORTED);\n}\n",
		"crates/util/src/real.rs":      "fn start() {\n    crate::mac_only();\n}\n",
		"crates/util/src/gated.rs":     "#![cfg(windows)]\n\nfn start() {\n    crate::gated_only();\n}\n",
		"crates/util/src/sys/imp.rs":   "fn start() {\n    crate::unix_only();\n}\n",
		"crates/util/src/generated.rs": "// Code generated by a tool. DO NOT EDIT.\n\npub use crate::text::gen_reexported;\n",
		"crates/util/src/bin/cli.rs":   "fn main() {\n    util::text::run(&util::Store);\n    println!(\"{}\", util::SHOWN);\n}\n",
		"crates/util/tests/it.rs":      "#[test]\nfn works() {\n    util::tested();\n}\n",
		"crates/app/Cargo.toml":        "[package]\nname = \"app\"\npublish.workspace = true\n",
		"crates/app/src/main.rs":       "pub fn local() {}\n\nfn main() {\n    local();\n    util::shared();\n}\n",
		"crates/open/Cargo.toml":       "[package]\nname = \"open\"\n",
		"crates/open/src/lib.rs":       "pub fn api() {}\n\npub fn caller() {\n    api();\n}\n",
	})

	_, stdout, _ := run("check", "--format", "json", root)

	testutil.Lines(t, "too public", candidateLines(decode(t, stdout), "too-public"), []string{
		"rust too-public [crates/util/src/lib.rs Store::reset]",
		"rust too-public [crates/util/src/lib.rs helper]",
		"rust too-public [crates/util/src/lib.rs LIMIT]",
	})
}

// The library is the module tree of its root file. A binary's modules
// (mod cli; from src/main.rs, a [[bin]] path under src/) are outside it,
// and so is another library of the same name. A root the manifest names
// has its modules beside it.
func TestCheckReportsRustItemsOnlyTheirLibraryModulesUse(t *testing.T) {
	root := repo(t, map[string]string{
		"app/Cargo.toml":     "[package]\nname = \"app\"\npublish = false\n\n[[bin]]\nname = \"tool\"\npath = \"src/tool.rs\"\n",
		"app/src/lib.rs":     "pub mod util;\n\npub fn api() {\n    util::from_main_module();\n    util::from_placed_bin();\n    util::inner_only();\n}\n",
		"app/src/util.rs":    "pub fn from_main_module() {}\n\npub fn from_placed_bin() {}\n\npub fn inner_only() {}\n",
		"app/src/main.rs":    "mod cli;\n\nfn main() {\n    cli::run();\n}\n",
		"app/src/cli.rs":     "pub fn run() {\n    app::api();\n    app::util::from_main_module();\n}\n",
		"app/src/tool.rs":    "fn main() {\n    app::util::from_placed_bin();\n}\n",
		"a/Cargo.toml":       "[package]\nname = \"server\"\npublish = false\n",
		"a/src/lib.rs":       "pub fn shared_thing() {}\n\npub fn start() {\n    shared_thing();\n}\n",
		"b/Cargo.toml":       "[package]\nname = \"server\"\npublish = false\n",
		"b/src/lib.rs":       "pub fn run() {\n    shared_thing();\n}\n\nfn shared_thing() {}\n",
		"named/Cargo.toml":   "[package]\nname = \"named\"\npublish = false\n\n[lib]\npath = \"src/named.rs\"\n",
		"named/src/named.rs": "pub mod parts;\n\npub fn api() {\n    parts::named_inner();\n}\n",
		"named/src/parts.rs": "pub fn named_inner() {}\n",
	})

	_, stdout, _ := run("check", "--format", "json", root)

	testutil.Lines(t, "too public", candidateLines(decode(t, stdout), "too-public"), []string{
		"rust too-public [app/src/util.rs inner_only]",
		"rust too-public [named/src/parts.rs named_inner]",
	})
}

