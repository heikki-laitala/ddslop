// driftRepo checks errors with errors.Is in 30 functions and by message
// in one, in the same file, plus any other files given.
func driftRepo(t *testing.T, more ...string) string {
	t.Helper()
	var b strings.Builder
	b.WriteString("package store\n\nimport (\n\t\"errors\"\n\t\"strings\"\n)\n\nvar ErrMissing = errors.New(\"missing\")\n\n")
	for i := range 30 {
		fmt.Fprintf(&b, "func Is%d(err error) bool { return errors.Is(err, ErrMissing) }\n", i)
	}
	b.WriteString("func ByMessage(err error) bool { return strings.Contains(err.Error(), \"missing\") }\n")
	files := map[string]string{"store/s.go": b.String()}
	for i := 0; i+1 < len(more); i += 2 {
		files[more[i]] = more[i+1]
	}
	return repo(t, files)
}

func TestCheckReportsAnErrorCheckDriftingFromTheConvention(t *testing.T) {
	root := driftRepo(t)

	stdout, _ := runCode(t, 1, "check", "--format", "json", root)
	var r struct {
		Candidates []struct {
			Kind        string `json:"kind"`
			Concern     string `json:"concern"`
			Occurrences []struct {
				File      string `json:"file"`
				Name      string `json:"name"`
				StartLine int    `json:"start_line"`
			} `json:"occurrences"`
			Target *struct {
				Name      string `json:"name"`
				StartLine int    `json:"start_line"`
			} `json:"target"`
			Values     []string `json:"values"`
			Share      float64  `json:"share"`
			Suggestion struct {
				Action  string `json:"action"`
				Pattern string `json:"pattern"`
			} `json:"suggestion"`
		} `json:"candidates"`
	}
	decodeInto(t, stdout, &r)
	if len(r.Candidates) != 1 {
		t.Fatalf("candidates = %+v, want one drift", r.Candidates)
	}
	c := r.Candidates[0]
	if c.Kind != "convention-drift" || c.Concern != "error-checks" || c.Suggestion.Action != "follow-convention" || c.Suggestion.Pattern != "errors.Is/As" {
		t.Errorf("candidate = %+v, want a convention-drift on error-checks, following errors.Is/As", c)
	}
	if len(c.Occurrences) != 1 || c.Occurrences[0].Name != "ByMessage" || c.Occurrences[0].StartLine != 40 {
		t.Errorf("occurrences = %+v, want ByMessage's check at line 40", c.Occurrences)
	}
	if c.Target == nil || c.Target.Name != "Is29" || c.Target.StartLine != 39 {
		t.Errorf("target = %+v, want the nearest errors.Is check, Is29 at line 39", c.Target)
	}
	if strings.Join(c.Values, " ") != "message" {
		t.Errorf("values = %v, want the drifting form", c.Values)
	}
	if c.Share != 30.0/31 {
		t.Errorf("share = %v, want 30/31: the share of the checks the convention holds", c.Share)
	}
}

func driftCandidates(t *testing.T, args ...string) []string {
	t.Helper()
	_, stdout, _ := run(append([]string{"check", "--format", "json"}, args...)...)
	var r struct {
		Candidates []struct {
			Kind        string `json:"kind"`
			Occurrences []struct {
				File      string `json:"file"`
				Name      string `json:"name"`
				StartLine int    `json:"start_line"`
				EndLine   int    `json:"end_line"`
			} `json:"occurrences"`
		} `json:"candidates"`
	}
	decodeInto(t, stdout, &r)
	var out []string
	for _, c := range r.Candidates {
		if c.Kind == "convention-drift" {
			var lines []string
			for _, o := range c.Occurrences {
				lines = append(lines, fmt.Sprintf("%d-%d", o.StartLine, o.EndLine))
			}
			o := c.Occurrences[0]
			out = append(out, fmt.Sprintf("%s:%s %s", o.File, strings.Join(lines, ","), o.Name))
		}
	}
	return out
}

func TestDriftReadsTheCodeCheckAnalyses(t *testing.T) {
	root := driftRepo(t,
		"store/gen.go", "// Code generated by sqlc. DO NOT EDIT.\n\npackage store\n\nimport \"strings\"\n\nfunc Gen(err error) bool { return strings.Contains(err.Error(), \"x\") }\n",
		"store/s_test.go", "package store\n\nimport \"strings\"\n\nfunc helper(err error) bool { return strings.Contains(err.Error(), \"x\") }\n")

	if got := driftCandidates(t, root); strings.Join(got, ", ") != "store/s.go:40-40 ByMessage" {
		t.Errorf("drifts = %v, want only ByMessage: generated code and tests are not analysed", got)
	}
	if got := driftCandidates(t, "--tests", root); strings.Join(got, ", ") != "store/s.go:40-40 ByMessage" {
		t.Errorf("drifts with --tests = %v, want only ByMessage: one test check is too few for a convention of test code's own", got)
	}
}

func TestDriftsOfOneFormInOneFunctionAreOneCandidate(t *testing.T) {
	root := driftRepo(t,
		"store/t.go", "package store\n\nimport \"strings\"\n\nfunc Twice(err error) bool {\n\treturn strings.Contains(err.Error(), \"a\") ||\n\t\tstrings.Contains(err.Error(), \"b\")\n}\n")

	if got := driftCandidates(t, root); strings.Join(got, ", ") != "store/s.go:40-40 ByMessage, store/t.go:6-6,7-7 Twice" {
		t.Errorf("drifts = %v, want Twice's two checks as one candidate with an occurrence on each line", got)
	}
	_, text, _ := run("check", "--format", "text", root)
	wantContains(t, text, "convention-drift: 2 place(s) using message (convention at 91%), follow-convention")
}

// Test code has conventions of its own: ten test helpers checking errors
// by message neither move production's convention nor drift from it, and
// --tests reports a test that checks otherwise among them.
func TestTestCodeHasConventionsOfItsOwn(t *testing.T) {
	var b strings.Builder
	b.WriteString("package store\n\nimport (\n\t\"errors\"\n\t\"strings\"\n)\n\n")
	for i := range 10 {
		fmt.Fprintf(&b, "func helper%d(err error) bool { return strings.Contains(err.Error(), \"x\") }\n", i)
	}
	b.WriteString("func helperIs(err error) bool { return errors.Is(err, ErrMissing) }\n")
	root := driftRepo(t, "store/s_test.go", b.String())

	if got := driftCandidates(t, root); strings.Join(got, ", ") != "store/s.go:40-40 ByMessage" {
		t.Errorf("drifts = %v, want only ByMessage without --tests", got)
	}
	if got := driftCandidates(t, "--tests", root); strings.Join(got, ", ") != "store/s.go:40-40 ByMessage, store/s_test.go:18-18 helperIs" {
		t.Errorf("drifts with --tests = %v, want ByMessage and the test checking by variant among tests checking by message", got)
	}
}

// errorChecks is a Go file of n functions checking errors with errors.Is
// and m checking them by message, named with prefix.
func errorChecks(prefix string, n, m int) string {
	var b strings.Builder
	b.WriteString("package store\n\nimport (\n\t\"errors\"\n\t\"strings\"\n)\n\n")
	for i := range n {
		fmt.Fprintf(&b, "func %sIs%d(err error) bool { return errors.Is(err, ErrMissing) }\n", prefix, i)
	}
	for i := range m {
		fmt.Fprintf(&b, "func %sByMessage%d(err error) bool { return strings.Contains(err.Error(), \"x\") }\n", prefix, i)
	}
	return b.String()
}

// A gate judges a change by the conventions the code it started from has:
// a change that brings a concern's share up to the drift share makes no
// drift of the code it did not touch, and one that brings it down still
// has its own drifts reported.
func TestBaselineRefJudgesDriftsByTheBaseConventions(t *testing.T) {
	sentinel := "package store\n\nimport \"errors\"\n\nvar ErrMissing = errors.New(\"missing\")\n"
	cases := []struct {
		name       string
		base, more [2]int // checks by errors.Is and by message, at the base and added
		want       []string
	}{
		// 30 of 35 at the base, no convention; 50 of 55 after.
		{name: "rising", base: [2]int{30, 5}, more: [2]int{20, 0}, want: nil},
		// 30 of 31 at the base; 30 of 35 after, below the drift share.
		{name: "falling", base: [2]int{30, 1}, more: [2]int{0, 4},
			want: []string{"store/new.go:8-8 NewByMessage0", "store/new.go:9-9 NewByMessage1",
				"store/new.go:10-10 NewByMessage2", "store/new.go:11-11 NewByMessage3"}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := committedRepo(t, map[string]string{
				"store/e.go": sentinel,
				"store/s.go": errorChecks("Old", tc.base[0], tc.base[1]),
			})
			testutil.WriteFiles(t, root, map[string]string{"store/new.go": errorChecks("New", tc.more[0], tc.more[1])})

			if got := driftCandidates(t, "--baseline-ref", "HEAD", root); strings.Join(got, ", ") != strings.Join(tc.want, ", ") {
				t.Errorf("drifts = %v, want %v", got, tc.want)
			}
		})
	}
}

// A ddslop:ignore on a drift's line leaves that line out and nothing else:
// the function's other drift and its code stay analysed.
func TestAnIgnoredLineIsNoDrift(t *testing.T) {
	root := driftRepo(t, "store/m.go", "package store\n\nimport \"strings\"\n\n"+
		"func Says(err error) bool {\n"+
		"\tif strings.Contains(err.Error(), \"a\") { // ddslop:ignore asserts the message the user reads\n\t\treturn true\n\t}\n"+
		"\treturn strings.Contains(err.Error(), \"b\")\n}\n")

	if got := driftCandidates(t, root); strings.Join(got, ", ") != "store/m.go:9-9 Says, store/s.go:40-40 ByMessage" {
		t.Errorf("drifts = %v, want Says's unmarked check and ByMessage", got)
	}
}
