// driftRepo checks errors with errors.Is in 30 functions and by message
// in one, in the same file, plus any other files given.
func driftRepo(t *testing.T, more ...string) string {
	t.Helper()
	var b strings.Builder
	b.WriteString("package store\n\nimport (\n\t\"errors\"\n\t\"strings\"\n)\n\nvar ErrMissing = errors.New(\"missing\")\n\n")
	for i := range 30 {
		fmt.Fprintf(&b, "func Is%d(err error) bool { return errors.Is(err, ErrMissing) }\n", i)
	}
	b.WriteString("func ByMessage(err error) bool { return strings.Contains(err.Error(), \"missing\") }\n")
	files := map[string]string{"store/s.go": b.String()}
	for i := 0; i+1 < len(more); i += 2 {
		files[more[i]] = more[i+1]
	}
	return repo(t, files)
}

func TestCheckReportsAnErrorCheckDriftingFromTheConvention(t *testing.T) {
	root := driftRepo(t)

	code, stdout, stderr := run("check", "--format", "json", root)
	if code != 1 {
		t.Fatalf("exit code = %d, want 1; stderr = %s", code, stderr)
	}
	var r struct {
		Candidates []struct {
			Kind        string `json:"kind"`
			Concern     string `json:"concern"`
			Occurrences []struct {
				File      string `json:"file"`
				Name      string `json:"name"`
				StartLine int    `json:"start_line"`
			} `json:"occurrences"`
			Target *struct {
				Name      string `json:"name"`
				StartLine int    `json:"start_line"`
			} `json:"target"`
			Values     []string `json:"values"`
			Suggestion struct {
				Action  string `json:"action"`
				Pattern string `json:"pattern"`
			} `json:"suggestion"`
		} `json:"candidates"`
	}
	decodeInto(t, stdout, &r)
	if len(r.Candidates) != 1 {
		t.Fatalf("candidates = %+v, want one drift", r.Candidates)
	}
	c := r.Candidates[0]
	if c.Kind != "convention-drift" || c.Concern != "error-checks" || c.Suggestion.Action != "follow-convention" || c.Suggestion.Pattern != "errors.Is/As" {
		t.Errorf("candidate = %+v, want a convention-drift on error-checks, following errors.Is/As", c)
	}
	if len(c.Occurrences) != 1 || c.Occurrences[0].Name != "ByMessage" || c.Occurrences[0].StartLine != 40 {
		t.Errorf("occurrences = %+v, want ByMessage's check at line 40", c.Occurrences)
	}
	if c.Target == nil || c.Target.Name != "Is29" || c.Target.StartLine != 39 {
		t.Errorf("target = %+v, want the nearest errors.Is check, Is29 at line 39", c.Target)
	}
	if strings.Join(c.Values, " ") != "message" {
		t.Errorf("values = %v, want the drifting form", c.Values)
	}
}

func driftCandidates(t *testing.T, stdout string) []string {
	t.Helper()
	var r struct {
		Candidates []struct {
			Kind        string `json:"kind"`
			Occurrences []struct {
				File      string `json:"file"`
				Name      string `json:"name"`
				StartLine int    `json:"start_line"`
				EndLine   int    `json:"end_line"`
			} `json:"occurrences"`
		} `json:"candidates"`
	}
	decodeInto(t, stdout, &r)
	var out []string
	for _, c := range r.Candidates {
		if c.Kind == "convention-drift" {
			var lines []string
			for _, o := range c.Occurrences {
				lines = append(lines, fmt.Sprintf("%d-%d", o.StartLine, o.EndLine))
			}
			o := c.Occurrences[0]
			out = append(out, fmt.Sprintf("%s:%s %s", o.File, strings.Join(lines, ","), o.Name))
		}
	}
	return out
}

func TestDriftReadsTheCodeCheckAnalyses(t *testing.T) {
	root := driftRepo(t,
		"store/gen.go", "// Code generated by sqlc. DO NOT EDIT.\n\npackage store\n\nimport \"strings\"\n\nfunc Gen(err error) bool { return strings.Contains(err.Error(), \"x\") }\n",
		"store/s_test.go", "package store\n\nimport \"strings\"\n\nfunc helper(err error) bool { return strings.Contains(err.Error(), \"x\") }\n")

	_, stdout, _ := run("check", "--format", "json", root)
	if got := driftCandidates(t, stdout); strings.Join(got, ", ") != "store/s.go:40-40 ByMessage" {
		t.Errorf("drifts = %v, want only ByMessage: generated code and tests are not analysed", got)
	}
	_, stdout, _ = run("check", "--format", "json", "--tests", root)
	if got := driftCandidates(t, stdout); len(got) != 2 {
		t.Errorf("drifts with --tests = %v, want ByMessage and the test helper", got)
	}
}

func TestDriftsOfOneFormInOneFunctionAreOneCandidate(t *testing.T) {
	root := driftRepo(t,
		"store/t.go", "package store\n\nimport \"strings\"\n\nfunc Twice(err error) bool {\n\treturn strings.Contains(err.Error(), \"a\") ||\n\t\tstrings.Contains(err.Error(), \"b\")\n}\n")

	_, stdout, _ := run("check", "--format", "json", root)
	if got := driftCandidates(t, stdout); strings.Join(got, ", ") != "store/s.go:40-40 ByMessage, store/t.go:6-6,7-7 Twice" {
		t.Errorf("drifts = %v, want Twice's two checks as one candidate with an occurrence on each line", got)
	}
}
