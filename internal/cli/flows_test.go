const generatedAPI = `// @generated by the OpenAPI generator. Do not edit.
pub trait LedgerApi {
    async fn create(&self, id: u64) -> u64;
}
`

const ledgerImpl = `pub struct Api;

impl LedgerApi for Api {
    async fn create(&self, id: u64) -> u64 {
        let checked = validate(id);
        Store::save(checked);
        self.audit(checked)
    }
}

impl Api {
    fn audit(&self, id: u64) -> u64 {
        id
    }
}

fn validate(id: u64) -> u64 {
    normalise(id)
}

fn normalise(id: u64) -> u64 {
    id
}

fn unrelated() {}
`

const storeImpl = `pub struct Store;

impl Store {
    pub fn save(id: u64) {}
}
`

type flowsOutput struct {
	Flows []struct {
		Entry struct {
			File string `json:"file"`
			Name string `json:"name"`
		} `json:"entry"`
		Steps []struct {
			Name   string `json:"name"`
			Depth  int    `json:"depth"`
			Caller string `json:"caller"`
		} `json:"steps"`
	} `json:"flows"`
	Summary struct {
		Entries       int `json:"entries"`
		Functions     int `json:"functions"`
		Calls         int `json:"calls"`
		ResolvedCalls int `json:"resolved_calls"`
	} `json:"summary"`
}

func TestFlowsFollowsEntryPointsOfGeneratedTraits(t *testing.T) {
	root := repo(t, map[string]string{
		"api/src/generated/server.rs": generatedAPI,
		"svc/src/ledger.rs":           ledgerImpl,
		"svc/src/store.rs":            storeImpl,
	})

	code, stdout, stderr := run("flows", "--format", "json", root)

	if code != 0 {
		t.Fatalf("flows: exit %d, stderr %s", code, stderr)
	}
	var r flowsOutput
	if err := json.Unmarshal([]byte(stdout), &r); err != nil {
		t.Fatalf("output is not JSON: %v\n%s", err, stdout)
	}
	if len(r.Flows) != 1 || r.Flows[0].Entry.Name != "Api::create" {
		t.Fatalf("flows = %+v, want one entry Api::create", r.Flows)
	}
	var steps []string
	for _, s := range r.Flows[0].Steps {
		steps = append(steps, s.Name+"<-"+s.Caller)
	}
	// Depth first: each function follows the one that called it.
	want := "Api::create<- validate<-Api::create normalise<-validate Store::save<-Api::create Api::audit<-Api::create"
	if strings.Join(steps, " ") != want {
		t.Errorf("steps = %v\nwant %s", steps, want)
	}
	if r.Summary.Entries != 1 || r.Summary.Calls != 4 || r.Summary.ResolvedCalls != 4 {
		t.Errorf("summary = %+v, want 1 entry and 4 of 4 calls resolved", r.Summary)
	}
}

func TestFlowsTextAndDepth(t *testing.T) {
	root := repo(t, map[string]string{
		"api/src/generated/server.rs": generatedAPI,
		"svc/src/ledger.rs":           ledgerImpl,
		"svc/src/store.rs":            storeImpl,
	})

	_, stdout, _ := run("flows", "--format", "text", "--depth", "1", root)

	for _, want := range []string{"Api::create (svc/src/ledger.rs:4-8)", "  validate (svc/src/ledger.rs:17-19)", "  Store::save (svc/src/store.rs:4-4)"} {
		if !strings.Contains(stdout, want) {
			t.Errorf("text output is missing %q:\n%s", want, stdout)
		}
	}
	if strings.Contains(stdout, "normalise") {
		t.Errorf("--depth 1 followed calls two levels deep:\n%s", stdout)
	}
}

func TestFlowsTextNestsEachFunctionUnderItsCaller(t *testing.T) {
	root := repo(t, map[string]string{
		"api/src/generated/server.rs": generatedAPI,
		"svc/src/ledger.rs":           ledgerImpl,
		"svc/src/store.rs":            storeImpl,
	})

	_, stdout, _ := run("flows", "--format", "text", root)

	// validate calls normalise, so normalise belongs right under validate,
	// before the entry's next callee, not after the last depth-1 function.
	want := "Api::create (svc/src/ledger.rs:4-8)\n" +
		"  validate (svc/src/ledger.rs:17-19)\n" +
		"    normalise (svc/src/ledger.rs:21-23)\n" +
		"  Store::save (svc/src/store.rs:4-4)\n" +
		"  Api::audit (svc/src/ledger.rs:12-14)\n"
	if !strings.Contains(stdout, want) {
		t.Errorf("flows text is not a call tree:\n%s\nwant it to contain:\n%s", stdout, want)
	}
}

func TestFlowsUseCargoCrateNames(t *testing.T) {
	// The directory is keyring/, but the crate is named acme_keyring.
	root := repo(t, map[string]string{
		"api/src/generated/server.rs": generatedAPI,
		"keyring/Cargo.toml":          "[package]\nname = \"acme-keyring\"\n",
		"keyring/src/lib.rs":          "pub fn is_canonical(id: u64) -> bool {\n    id > 0\n}\n",
		"svc/src/ledger.rs": `pub struct Api;

impl LedgerApi for Api {
    async fn create(&self, id: u64) -> u64 {
        acme_keyring::is_canonical(id);
        id
    }
}
`,
	})

	_, stdout, _ := run("flows", "--format", "text", root)

	if !strings.Contains(stdout, "  is_canonical (keyring/src/lib.rs:1-3)") {
		t.Errorf("the call into acme_keyring was not followed:\n%s", stdout)
	}
}

func TestFlowsIgnoreDependenciesOnlyTestsUse(t *testing.T) {
	// svc's tests use the ledger crate; svc's own code does not, so its
	// client.settle() is not the ledger's Settles::settle.
	root := repo(t, map[string]string{
		"api/src/generated/server.rs": generatedAPI,
		"ledger/src/lib.rs":           "pub struct Settles;\n\nimpl Settles {\n    pub fn settle(&self) {}\n}\n",
		"svc/src/tests.rs":            "use ledger::Settles;\n\nfn it() {}\n",
		"svc/src/lib.rs": `pub struct Api;

impl LedgerApi for Api {
    async fn create(&self, id: u64) -> u64 {
        self.client.settle();
        id
    }
}
`,
	})

	_, stdout, _ := run("flows", "--format", "text", root)

	if strings.Contains(stdout, "Settles::settle") {
		t.Errorf("a dependency only tests use was followed:\n%s", stdout)
	}
}

// A test package in the same directory may declare a struct like a
// production one; its fields must not retype production calls.
func TestGraphInputsLeaveOutTestFieldTypes(t *testing.T) {
	files := []index.File{
		{Path: "api/server.go", Parsed: index.Parsed{Decls: unit.Decls{FieldTypes: []unit.FieldType{{Struct: "Server", Field: "store", Type: "Store"}}}}},
		{Path: "api/server_test.go", Parsed: index.Parsed{Decls: unit.Decls{FieldTypes: []unit.FieldType{{Struct: "Server", Field: "store", Type: "Fake", Test: true}}}}},
	}
	if got := graphInputs(t.TempDir(), files).Fields["api"]["Server.store"]; got != "Store" {
		t.Errorf("Server.store = %q, want the production type Store", got)
	}
}

// Two modules of a Rust crate may declare structs of one name: a field
// they type differently is unknown rather than either's.
func TestGraphInputsLeaveFieldsOfCollidingStructsUntyped(t *testing.T) {
	fields := func(path, typ string) index.File {
		return index.File{Path: path, Parsed: index.Parsed{Decls: unit.Decls{FieldTypes: []unit.FieldType{{Struct: "Server", Field: "db", Type: typ}}}}}
	}
	in := graphInputs(t.TempDir(), []index.File{
		fields("a/src/one.rs", "Database"), fields("a/src/two.rs", "Cache"),
		fields("b/src/one.rs", "Database"), fields("b/src/two.rs", "Database"),
	})
	if got, ok := in.Fields["a"]["Server.db"]; !ok || got != "" {
		t.Errorf("a's Server.db = %q (present %v), want \"\": two structs type it differently", got, ok)
	}
	if got := in.Fields["b"]["Server.db"]; got != "Database" {
		t.Errorf("b's Server.db = %q, want Database: both agree", got)
	}
}

