package cli

import (
	"encoding/json"
	"strings"
	"testing"
)

const generatedAPI = `// @generated by the OpenAPI generator. Do not edit.
pub trait LedgerApi {
    async fn create(&self, id: u64) -> u64;
}
`

const ledgerImpl = `pub struct Api;

impl LedgerApi for Api {
    async fn create(&self, id: u64) -> u64 {
        let checked = validate(id);
        Store::save(checked);
        self.audit(checked)
    }
}

impl Api {
    fn audit(&self, id: u64) -> u64 {
        id
    }
}

fn validate(id: u64) -> u64 {
    normalise(id)
}

fn normalise(id: u64) -> u64 {
    id
}

fn unrelated() {}
`

const storeImpl = `pub struct Store;

impl Store {
    pub fn save(id: u64) {}
}
`

type flowsOutput struct {
	Flows []struct {
		Entry struct {
			File string `json:"file"`
			Name string `json:"name"`
		} `json:"entry"`
		Steps []struct {
			Name   string `json:"name"`
			Depth  int    `json:"depth"`
			Caller string `json:"caller"`
		} `json:"steps"`
	} `json:"flows"`
	Summary struct {
		Entries       int `json:"entries"`
		Functions     int `json:"functions"`
		Calls         int `json:"calls"`
		ResolvedCalls int `json:"resolved_calls"`
	} `json:"summary"`
}

func TestFlowsFollowsEntryPointsOfGeneratedTraits(t *testing.T) {
	root := repo(t, map[string]string{
		"api/src/generated/server.rs": generatedAPI,
		"svc/src/ledger.rs":           ledgerImpl,
		"svc/src/store.rs":            storeImpl,
	})

	code, stdout, stderr := run("flows", "--format", "json", root)

	if code != 0 {
		t.Fatalf("flows: exit %d, stderr %s", code, stderr)
	}
	var r flowsOutput
	if err := json.Unmarshal([]byte(stdout), &r); err != nil {
		t.Fatalf("output is not JSON: %v\n%s", err, stdout)
	}
	if len(r.Flows) != 1 || r.Flows[0].Entry.Name != "Api::create" {
		t.Fatalf("flows = %+v, want one entry Api::create", r.Flows)
	}
	var steps []string
	for _, s := range r.Flows[0].Steps {
		steps = append(steps, s.Name+"<-"+s.Caller)
	}
	want := "Api::create<- validate<-Api::create Store::save<-Api::create Api::audit<-Api::create normalise<-validate"
	if strings.Join(steps, " ") != want {
		t.Errorf("steps = %v\nwant %s", steps, want)
	}
	if r.Summary.Entries != 1 || r.Summary.Calls != 4 || r.Summary.ResolvedCalls != 4 {
		t.Errorf("summary = %+v, want 1 entry and 4 of 4 calls resolved", r.Summary)
	}
}

func TestFlowsTextAndDepth(t *testing.T) {
	root := repo(t, map[string]string{
		"api/src/generated/server.rs": generatedAPI,
		"svc/src/ledger.rs":           ledgerImpl,
		"svc/src/store.rs":            storeImpl,
	})

	_, stdout, _ := run("flows", "--format", "text", "--depth", "1", root)

	for _, want := range []string{"Api::create (svc/src/ledger.rs:4-8)", "  validate (svc/src/ledger.rs:17-19)", "  Store::save (svc/src/store.rs:4-4)"} {
		if !strings.Contains(stdout, want) {
			t.Errorf("text output is missing %q:\n%s", want, stdout)
		}
	}
	if strings.Contains(stdout, "normalise") {
		t.Errorf("--depth 1 followed calls two levels deep:\n%s", stdout)
	}
}
