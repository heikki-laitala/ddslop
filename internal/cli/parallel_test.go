const featureAPI = `// @generated by the OpenAPI generator. Do not edit.
pub trait FeatureApi {
    async fn create(&self, id: u64) -> Result<u64, E>;
}
`

const featureService = `impl FeatureApi for Service {
    async fn create(&self, id: u64) -> Result<u64, E> {
        let v = validate_create(id)?;
        let f = fingerprint_create(v);
        persist_create(f)
    }

    async fn update(&self, key: u64) -> Result<u64, E> {
        let checked = validate_update(key)?;
        let print = fingerprint_update(checked);
        persist_update(print)
    }

    async fn health(&self) -> u64 {
        1
    }
}

fn validate_create(id: u64) -> Result<u64, E> {
    if id == 0 {
        return Err(E::Zero);
    }
    if id > 1000 {
        return Err(E::Large);
    }
    Ok(id)
}

fn validate_update(key: u64) -> Result<u64, E> {
    if key == 0 {
        return Err(E::Missing);
    }
    if key > 5000 {
        return Err(E::TooLarge);
    }
    Ok(key)
}

fn fingerprint_create(v: u64) -> String {
    let mut out = String::new();
    for b in v.to_be_bytes() {
        out.push_str(&format!("{b:02x}"));
    }
    out
}

fn fingerprint_update(v: u64) -> String {
    let mut text = String::new();
    for byte in v.to_be_bytes() {
        text.push_str(&format!("{byte:02x}"));
    }
    text
}

fn persist_create(f: String) -> Result<u64, E> {
    let key = format!("create:{f}");
    store_write(&key)?;
    Ok(f.len() as u64)
}

fn persist_update(f: String) -> Result<u64, E> {
    let key = format!("update:{f}");
    store_write(&key)?;
    Ok(f.len() as u64)
}

fn store_write(key: &str) -> Result<(), E> {
    if key.is_empty() {
        return Err(E::Empty);
    }
    Ok(())
}
`

type flowCandidate struct {
	Kind        string `json:"kind"`
	Occurrences []struct {
		File string `json:"file"`
		Name string `json:"name"`
	} `json:"occurrences"`
	Steps []struct {
		Occurrences []struct {
			File       string  `json:"file"`
			Name       string  `json:"name"`
			Similarity float64 `json:"similarity"`
			Changed    bool    `json:"changed"`
		} `json:"occurrences"`
	} `json:"steps"`
	Suggestion struct {
		Action string `json:"action"`
	} `json:"suggestion"`
}

func flowCandidates(t *testing.T, stdout string) []flowCandidate {
	t.Helper()
	var r struct {
		Candidates []flowCandidate `json:"candidates"`
	}
	decodeInto(t, stdout, &r)
	var out []flowCandidate
	for _, c := range r.Candidates {
		if c.Kind == "parallel-flow" {
			out = append(out, c)
		}
	}
	return out
}

func featureRepo(t *testing.T) string {
	t.Helper()
	return repo(t, map[string]string{"api/src/generated/server.rs": featureAPI, "svc/src/lib.rs": featureService})
}

func TestCheckReportsParallelFlows(t *testing.T) {
	root := featureRepo(t)

	code, stdout, _ := run("check", "--format", "json", "--min-nodes", "10", root)

	if code != 1 {
		t.Fatalf("exit code = %d, want 1", code)
	}
	flows := flowCandidates(t, stdout)
	if len(flows) != 1 {
		t.Fatalf("got %d parallel flows, want 1", len(flows))
	}
	f := flows[0]
	if len(f.Occurrences) != 2 || f.Occurrences[0].Name != "Service::create" || f.Occurrences[1].Name != "Service::update" {
		t.Errorf("occurrences = %+v, want the two entry points", f.Occurrences)
	}
	if f.Suggestion.Action != "extract-pipeline" {
		t.Errorf("suggestion = %q, want extract-pipeline", f.Suggestion.Action)
	}
	var steps []string
	for _, s := range f.Steps {
		var names []string
		for _, o := range s.Occurrences {
			names = append(names, o.Name)
		}
		steps = append(steps, strings.Join(names, "|"))
	}
	want := "Service::create|Service::update validate_create|validate_update fingerprint_create|fingerprint_update persist_create|persist_update"
	if strings.Join(steps, " ") != want {
		t.Errorf("steps = %v\nwant %s", steps, want)
	}
}

func TestCheckDiffKeepsParallelFlowsWhoseStepsChanged(t *testing.T) {
	root := committedRepo(t, map[string]string{"api/src/generated/server.rs": featureAPI, "svc/src/lib.rs": featureService})
	changed := strings.Replace(featureService, `let key = format!("update:{f}");`, `let key = format!("update-v2:{f}");`, 1)
	if err := os.WriteFile(filepath.Join(root, "svc/src/lib.rs"), []byte(changed), 0o600); err != nil {
		t.Fatal(err)
	}

	_, stdout, _ := run("check", "--format", "json", "--min-nodes", "10", "--diff", "HEAD", root)

	flows := flowCandidates(t, stdout)
	if len(flows) != 1 {
		t.Fatalf("got %d parallel flows, want the one whose persist step changed", len(flows))
	}
	var changedSteps []string
	for _, s := range flows[0].Steps {
		for _, o := range s.Occurrences {
			if o.Changed {
				changedSteps = append(changedSteps, o.Name)
			}
		}
	}
	if strings.Join(changedSteps, " ") != "persist_update" {
		t.Errorf("changed steps = %v, want [persist_update]", changedSteps)
	}
}

func TestCheckTextShowsParallelFlowSteps(t *testing.T) {
	root := featureRepo(t)

	_, stdout, _ := run("check", "--format", "text", "--min-nodes", "10", root)

	for _, want := range []string{"parallel-flow", "extract-pipeline", "step: svc/src/lib.rs:19-27 validate_create | svc/src/lib.rs:29-37 validate_update"} {
		if !strings.Contains(stdout, want) {
			t.Errorf("text output is missing %q:\n%s", want, stdout)
		}
	}
}
